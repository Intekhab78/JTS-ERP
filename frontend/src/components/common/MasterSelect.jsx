import React, { useState, useRef } from 'react';
import Select, { components } from 'react-select';
import { Edit2, Trash2, Plus, X, Save, Sparkles } from 'lucide-react';
import axios from 'axios';

export const generateCodeFromName = (name) => {
  if (!name || typeof name !== 'string') return '';
  const clean = name.trim().replace(/[^a-zA-Z0-9\s]/g, '').toUpperCase();
  const words = clean.split(/\s+/).filter(Boolean);
  if (words.length === 0) return '';
  if (words.length === 1) {
    return words[0].slice(0, 10);
  }
  const parts = words.slice(0, 3).map(w => w.slice(0, 4));
  return parts.join('-');
};

export const MasterSelect = ({ 
  options, 
  value, 
  onChange, 
  endpoint, 
  title, 
  onRefresh, 
  fields = [{ name: 'name', label: 'Name' }, { name: 'code', label: 'Code' }],
  isDisabled = false,
  placeholder = 'Select...',
  extraPayload = {},
  parent = null, // { label: 'Department', name: 'itemDepartmentId', value: '...', displayValue: '...', options: [...] }
  onCreated = null
}) => {
  const selectRef = useRef(null);
  const [isModalOpen, setIsModalOpen] = useState(false);
  const [isEditing, setIsEditing] = useState(false);
  const [editId, setEditId] = useState(null);
  const [formData, setFormData] = useState({});
  const [loading, setLoading] = useState(false);
  const [codeAutoGenerated, setCodeAutoGenerated] = useState(true);

  const customStyles = {
    control: (provided, state) => ({
      ...provided,
      backgroundColor: '#ffffff',
      border: '1px solid',
      borderColor: state.isFocused ? '#3b82f6' : '#cbd5e1',
      boxShadow: 'none',
      minHeight: '34px',
      height: '34px',
      borderRadius: '0.375rem',
      fontSize: '0.8125rem',
      fontWeight: '500',
      color: '#0f172a',
      cursor: state.isDisabled ? 'not-allowed' : 'pointer',
      '&:hover': {
        borderColor: state.isFocused ? '#3b82f6' : '#94a3b8'
      }
    }),
    valueContainer: (provided) => ({
      ...provided,
      padding: '0 8px',
      height: '34px',
    }),
    input: (provided) => ({
      ...provided,
      margin: '0',
      padding: '0',
    }),
    indicatorsContainer: (provided) => ({
      ...provided,
      height: '34px',
    }),
    option: (provided, state) => ({
      ...provided,
      fontSize: '0.875rem',
      fontWeight: '700',
      backgroundColor: state.isSelected ? '#2563eb' : state.isFocused ? '#eff6ff' : 'white',
      color: state.isSelected ? 'white' : '#0f172a',
      cursor: 'pointer',
      display: 'flex',
      justifyContent: 'space-between',
      alignItems: 'center'
    }),
    menu: (provided) => ({
      ...provided,
      borderRadius: '0.375rem',
      boxShadow: '0 10px 15px -3px rgba(0, 0, 0, 0.1), 0 4px 6px -2px rgba(0, 0, 0, 0.05)',
      zIndex: 9999,
      border: '2px solid #e2e8f0',
      overflow: 'hidden'
    }),
    menuPortal: base => ({ ...base, zIndex: 9999 }),
  };

  const openAddModal = () => {
    if (selectRef.current) {
      selectRef.current.blur();
    }
    const initialData = {};
    if (parent && parent.name) {
      initialData[parent.name] = parent.value || '';
    }
    setFormData(initialData);
    setIsEditing(false);
    setEditId(null);
    setCodeAutoGenerated(true);
    setIsModalOpen(true);
  };

  const openEditModal = (e, opt) => {
    e.preventDefault();
    e.stopPropagation();
    if (selectRef.current) {
      selectRef.current.blur();
    }
    const orig = opt.original || {};
    const initialData = { ...orig };
    if (parent && parent.name) {
      const origParentVal = orig[parent.name]?._id || orig[parent.name];
      initialData[parent.name] = origParentVal || parent.value || '';
    }
    setFormData(initialData);
    setIsEditing(true);
    const id = orig._id || opt.value;
    setEditId(id);
    setCodeAutoGenerated(false);
    setIsModalOpen(true);
  };

  const handleDelete = async (e, id, label) => {
    e.preventDefault();
    e.stopPropagation();
    if (selectRef.current) {
      selectRef.current.blur();
    }
    if (window.confirm(`Are you sure you want to delete this ${title}?`)) {
      try {
        await axios.delete(`${endpoint}/${encodeURIComponent(id)}`, {
          headers: { Authorization: `Bearer ${localStorage.getItem('token')}` }
        });
        if (value === id || value === label) onChange(''); // Clear selection if deleted
        if (onRefresh) onRefresh();
      } catch (err) {
        alert(`Failed to delete ${title}: ` + (err.response?.data?.message || err.message));
      }
    }
  };

  const handleFieldChange = (fieldName, val) => {
    const updated = { ...formData, [fieldName]: val };
    const codeField = fields.find(f => f.name.toLowerCase().includes('code'));
    const isName = fieldName.toLowerCase().includes('name');

    if (codeField && isName) {
      if (codeAutoGenerated || !formData[codeField.name]) {
        updated[codeField.name] = generateCodeFromName(val);
      }
    }

    if (codeField && fieldName === codeField.name) {
      setCodeAutoGenerated(val.trim() === '');
    }

    setFormData(updated);
  };

  const handleAutoGenerateCode = (codeFieldName) => {
    const nameField = fields.find(f => f.name.toLowerCase().includes('name')) || fields[0];
    const nameVal = formData[nameField?.name] || '';
    const generated = generateCodeFromName(nameVal);
    setFormData(prev => ({ ...prev, [codeFieldName]: generated }));
    setCodeAutoGenerated(true);
  };

  const handleSave = async () => {
    setLoading(true);
    try {
      const headers = { Authorization: `Bearer ${localStorage.getItem('token')}` };
      const payload = { ...extraPayload, ...formData };
      let res;
      if (isEditing) {
        res = await axios.put(`${endpoint}/${encodeURIComponent(editId)}`, payload, { headers });
      } else {
        res = await axios.post(endpoint, payload, { headers });
      }
      setIsModalOpen(false);
      if (onRefresh) {
        await onRefresh(res?.data, isEditing);
      }
      if (!isEditing && res?.data) {
        if (onCreated) {
          onCreated(res.data);
        } else {
          const createdId = res.data._id;
          const createdName = res.data.name;
          if (options.some(o => o.value === createdId)) {
            onChange(createdId);
          } else if (createdName) {
            onChange(createdName);
          }
        }
      }
    } catch (err) {
      alert(`Failed to save ${title}: ` + (err.response?.data?.message || err.message));
    } finally {
      setLoading(false);
    }
  };

  // Custom Option Component with Edit/Delete buttons
  const CustomOption = (props) => {
    const targetId = props.data.original?._id || props.data.value;
    return (
      <components.Option {...props}>
        <span className="truncate pr-2">{props.data.label}</span>
        <div className="flex items-center gap-1 opacity-60 hover:opacity-100 transition-opacity shrink-0">
          <button 
            type="button" 
            onClick={(e) => openEditModal(e, props.data)} 
            className="p-1 hover:text-blue-600 hover:bg-blue-100/60 rounded transition-colors"
            title={`Edit ${title}`}
          >
            <Edit2 size={13} />
          </button>
          <button 
            type="button" 
            onClick={(e) => handleDelete(e, targetId, props.data.label || props.data.value)} 
            className="p-1 hover:text-rose-600 hover:bg-rose-100/60 rounded transition-colors"
            title={`Delete ${title}`}
          >
            <Trash2 size={13} />
          </button>
        </div>
      </components.Option>
    );
  };

  // Custom Menu that pins "+ Add New" button at the TOP so it is never hidden behind scroll
  const CustomMenu = (props) => {
    return (
      <components.Menu {...props}>
        <div 
          onMouseDown={(e) => {
            e.preventDefault();
            e.stopPropagation();
            openAddModal();
          }}
          className="sticky top-0 z-30 px-3 py-2 bg-gradient-to-r from-blue-50 to-indigo-50 border-b-2 border-blue-200 text-blue-700 font-black text-xs uppercase tracking-wider cursor-pointer flex items-center justify-between hover:from-blue-100 hover:to-indigo-100 transition-all select-none shadow-xs group"
        >
          <div className="flex items-center gap-2">
            <span className="w-5 h-5 rounded bg-blue-600 text-white flex items-center justify-center shadow-xs group-hover:scale-105 transition-transform">
              <Plus size={13} strokeWidth={3} />
            </span>
            <span>+ Add New {title}</span>
          </div>
          <span className="text-[10px] bg-blue-100/80 text-blue-700 px-1.5 py-0.5 rounded font-mono font-bold tracking-tight">
            ADD
          </span>
        </div>
        {props.children}
      </components.Menu>
    );
  };

  const selectedOpt = options.find(o => o.value === value) || null;

  return (
    <>
      <Select
        ref={selectRef}
        value={selectedOpt}
        onChange={opt => onChange(opt ? opt.value : '')}
        options={options}
        styles={customStyles}
        components={{ Option: CustomOption, Menu: CustomMenu }}
        placeholder={placeholder}
        isDisabled={isDisabled}
        isClearable
        menuIsOpen={isModalOpen ? false : undefined}
        menuPortalTarget={document.body}
      />

      {isModalOpen && (
        <div className="fixed inset-0 z-[100000] flex items-center justify-center bg-black/60 backdrop-blur-xs p-4 animate-in fade-in duration-150">
          <div className="bg-white rounded-xl shadow-2xl w-full max-w-md overflow-hidden border-2 border-slate-200 animate-in zoom-in-95 duration-150">
            <div className="bg-slate-900 px-5 py-4 flex justify-between items-center border-b border-slate-800">
              <h3 className="text-white font-black uppercase tracking-widest text-sm flex items-center gap-2">
                <span className="w-2 h-2 rounded-full bg-blue-500"></span>
                {isEditing ? `Edit ${title}` : `New ${title}`}
              </h3>
              <button 
                type="button"
                onClick={() => setIsModalOpen(false)} 
                className="text-slate-400 hover:text-white p-1 rounded-md transition-colors"
              >
                <X size={18} />
              </button>
            </div>
            
            <div className="p-5 space-y-4 max-h-[75vh] overflow-y-auto">
              {/* Parent Selector / Display if configured */}
              {parent && (
                <div className="p-3 bg-slate-50 rounded-lg border border-slate-200">
                  <div className="flex items-center justify-between mb-1.5">
                    <label className="text-[10px] font-bold text-slate-600 uppercase tracking-widest flex items-center gap-1.5">
                      <span className="w-1.5 h-1.5 rounded-full bg-blue-500"></span>
                      {parent.label}
                    </label>
                    <span className="text-[10px] font-bold text-blue-600 uppercase">
                      Parent Hierarchy
                    </span>
                  </div>
                  {parent.options && parent.options.length > 0 ? (
                    <select
                      value={formData[parent.name] || ''}
                      onChange={e => setFormData({ ...formData, [parent.name]: e.target.value })}
                      className="w-full h-10 px-3 bg-white border-2 border-slate-200 rounded-md text-xs font-bold text-slate-900 outline-none uppercase focus:border-blue-600 transition-colors cursor-pointer"
                    >
                      <option value="">-- SELECT {parent.label.toUpperCase()} --</option>
                      {parent.options.map(pOpt => (
                        <option key={pOpt.value} value={pOpt.value}>{pOpt.label}</option>
                      ))}
                    </select>
                  ) : (
                    <div className="w-full h-10 px-3 bg-slate-100 border-2 border-slate-200 rounded-md flex items-center text-xs font-bold text-slate-800 uppercase">
                      {parent.displayValue || 'N/A'}
                    </div>
                  )}
                </div>
              )}

              {/* Form Fields with Code Auto-generation */}
              {fields.map(field => {
                const isCodeField = field.name.toLowerCase().includes('code');
                return (
                  <div key={field.name}>
                    <div className="flex items-center justify-between mb-1">
                      <label className="text-[10px] font-bold text-slate-500 uppercase tracking-widest block">
                        {field.label}
                      </label>
                      {isCodeField && (
                        <button
                          type="button"
                          onClick={() => handleAutoGenerateCode(field.name)}
                          className="text-[10px] font-bold text-blue-600 hover:text-blue-800 flex items-center gap-1 uppercase tracking-wider transition-colors"
                          title="Auto-generate code from name"
                        >
                          <Sparkles size={11} className="text-blue-500" /> Auto Generate
                        </button>
                      )}
                    </div>
                    <input
                      type="text"
                      value={formData[field.name] || ''}
                      onChange={e => handleFieldChange(field.name, e.target.value)}
                      placeholder={`ENTER ${field.label.toUpperCase()}`}
                      className={`w-full h-10 px-3 bg-slate-50 border-2 border-slate-200 rounded-md focus:border-blue-600 focus:bg-white focus:ring-0 text-sm font-bold text-slate-900 outline-none uppercase transition-colors ${isCodeField ? 'font-mono' : ''}`}
                    />
                  </div>
                );
              })}
            </div>

            <div className="px-5 py-4 bg-slate-50 border-t border-slate-200 flex justify-end gap-3">
              <button 
                type="button"
                onClick={() => setIsModalOpen(false)}
                className="px-4 py-2 bg-white border-2 border-slate-200 text-slate-600 text-xs font-bold uppercase tracking-widest rounded-md hover:bg-slate-100 transition-colors"
              >
                Cancel
              </button>
              <button 
                type="button"
                onClick={handleSave}
                disabled={loading}
                className="flex items-center gap-2 px-6 py-2 bg-blue-600 text-white text-xs font-bold uppercase tracking-widest rounded-md hover:bg-blue-500 shadow-md transition-colors disabled:opacity-50"
              >
                {loading ? 'Saving...' : <><Save size={14} /> Commit</>}
              </button>
            </div>
          </div>
        </div>
      )}
    </>
  );
};
